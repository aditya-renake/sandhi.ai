export function speakText(text, lang = "en") {
  if (typeof window === "undefined" || !("speechSynthesis" in window)) {
    return
  }

  try {
    window.speechSynthesis.cancel()

    const utterance = new SpeechSynthesisUtterance(text)
    const langConfig = VOICE_PROMPTS[lang] || VOICE_PROMPTS.en
    utterance.lang = langConfig.langCode || "en-IN"
    
    // Sweeter, warmer pitch and gentle pacing
    utterance.pitch = 1.15
    utterance.rate = 0.92

    const voices = window.speechSynthesis.getVoices()
    const preferredNames = ["Google UK English Female", "Samantha", "Karen", "Moira", "Victoria", "Lekha", "Veena", "Neerja"]
    let selectedVoice = voices.find(v => preferredNames.some(name => v.name.includes(name)))
    
    if (!selectedVoice) {
      selectedVoice = voices.find(v => v.lang.startsWith(langConfig.langCode.split("-")[0]))
    }
    
    if (selectedVoice) {
      utterance.voice = selectedVoice
    }

    window.speechSynthesis.speak(utterance)
  } catch (err) {
    console.warn("Speech synthesis notice:", err)
  }
}

export function speakRepPraise(repIndex, lang = "en") {
  const langConfig = VOICE_PROMPTS[lang] || VOICE_PROMPTS.en
  const praiseList = langConfig.repPraise || VOICE_PROMPTS.en.repPraise
  const praiseText = praiseList[Math.min(repIndex - 1, praiseList.length - 1)] || `${langConfig.name}: ${repIndex}`
  speakText(praiseText, lang)
}
